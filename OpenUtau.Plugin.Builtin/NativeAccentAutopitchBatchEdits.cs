using System;
using System.Collections.Generic;
using System.Linq;
using OpenUtau.Core;
using OpenUtau.Core.Editing;
using OpenUtau.Core.Ustx;

namespace OpenUtau.Plugin.Builtin {
    /// <summary>
    /// Base class for DELTA SYNTH Native Accent Autopitch BatchEdits
    /// </summary>
    public abstract class BaseNativeAutopitchBatchEdit : BatchEdit {
        public abstract string Name { get; }
        protected abstract LanguageFamily TargetLanguage { get; }

        public void Run(UProject project, UVoicePart part, List<UNote> selectedNotes, DocManager docManager) {
            var notes = (selectedNotes != null && selectedNotes.Count > 0)
                ? selectedNotes.OrderBy(n => n.position).ToList()
                : part.notes.OrderBy(n => n.position).ToList();

            if (notes.Count == 0) return;

            string? phonemizerTag = project.tracks.ElementAtOrDefault(part.trackNo)?.PhonemizerTag;

            docManager.StartUndoGroup("command.batch.note", true);
            try {
                for (int i = 0; i < notes.Count; i++) {
                    var note = notes[i];
                    UNote? prevNote = i > 0 ? notes[i - 1] : null;
                    UNote? nextNote = i < notes.Count - 1 ? notes[i + 1] : null;

                    double durationMs = project.timeAxis.MsBetweenTickPos(
                        part.position + note.position,
                        part.position + note.End);

                    LanguageFamily lang = TargetLanguage;
                    if (lang == LanguageFamily.AutoDetect) {
                        lang = LanguageAutopitchService.DetectLanguage(phonemizerTag, note.lyric ?? "");
                    }

                    var points = LanguageAutopitchService.GenerateNativePitchPoints(
                        note, prevNote, nextNote, durationMs, lang);

                    if (points.Count > 0) {
                        docManager.ExecuteCmd(new ResetPitchPointsCommand(part, note));
                        int index = 0;
                        foreach (var p in points) {
                            docManager.ExecuteCmd(new AddPitchPointCommand(part, note, p, index));
                            index++;
                        }
                        // Remove the 2 default points generated by ResetPitchPointsCommand
                        docManager.ExecuteCmd(new DeletePitchPointCommand(part, note, index));
                        docManager.ExecuteCmd(new DeletePitchPointCommand(part, note, index));
                    }

                    var vibrato = LanguageAutopitchService.GenerateNaturalVibrato(durationMs);
                    if (vibrato != null) {
                        docManager.ExecuteCmd(new SetVibratoCommand(part, note, vibrato));
                    }
                }

                docManager.ExecuteCmd(new ShowPitchNotification());
            } finally {
                docManager.EndUndoGroup();
            }
        }
    }

    /// <summary>
