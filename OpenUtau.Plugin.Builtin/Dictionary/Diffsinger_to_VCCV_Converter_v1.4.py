# v1.4 - 2026-07-18 - ฟังก์ชันปรับสมดุลไวยากรณ์ การออกเสียง และเพิ่มพื้นที่พยัญชนะ
def optimize_vocal_harmony(tokens):
    processed = [] # v1.4 - 2026-07-18 - สร้างลิสต์ว่างสำหรับเก็บหน่วยเสียงที่ผ่านการปรับสมดุลแล้ว
    total_tokens = len(tokens) # v1.4 - 2026-07-18 - นับจำนวนหน่วยเสียงทั้งหมดในคำนั้นๆ
    
    for i, token in enumerate(tokens): # v1.4 - 2026-07-18 - วนลูปอ่านค่าหน่วยเสียงทีละตัวพร้อมดัชนี
        is_last = (i == total_tokens - 1) # v1.4 - 2026-07-18 - ตรวจสอบว่าหน่วยเสียงนี้คือตำแหน่งสุดท้ายหรือไม่ (ตัวสะกด)
        
        if is_last: # v1.4 - 2026-07-18 - หากเป็นหน่วยเสียงในตำแหน่งตัวสะกด
            # v1.4 - 2026-07-18 - บังคับใช้ตัวสะกดภาษาไทยเป็น n, m, y, w, g, k, b, d ตามหลักไวยากรณ์อย่างเคร่งครัด
            ending_consonants = {'ng': 'g', 'm': 'm', 'n': 'n', 'w': 'w', 'y': 'y', 'k': 'k', 'K': 'k', 'p': 'b', 'B': 'b', 't': 'd', 'D': 'd'} # v1.4 - 2026-07-18 - แผนผังแมพตัวสะกด
            optimized_token = ending_consonants.get(token, phoneme_map.get(token, token)) # v1.4 - 2026-07-18 - แปลงค่าตัวสะกด หากไม่พบให้ใช้ค่ามาตรฐาน
            processed.append(optimized_token) # v1.4 - 2026-07-18 - เพิ่มตัวสะกดที่ปรับปรุงแล้วลงในลิสต์
        else:
            # v1.4 - 2026-07-18 - การจัดการพยัญชนะต้นและสระ
            mapped_token = phoneme_map.get(token, token) # v1.4 - 2026-07-18 - แปลงพยัญชนะต้นและสระเบื้องต้น
            processed.append(mapped_token) # v1.4 - 2026-07-18 - เพิ่มหน่วยเสียงลงในลิสต์เพื่อการจัดเรียง
            
    # v1.4 - 2026-07-18 - การจัดการเพิ่มพื้นที่พยัญชนะเพื่อร่างเส้นแดงและเอื้อนจังหวะเร็วตามธรรมชาติ
    # v1.4 - 2026-07-18 - หากระบบพบพยัญชนะควบกล้ำ จะทำการเว้นช่องว่างอย่างเหมาะสมให้ UTAU อ่านเป็นจังหวะเอื้อนได้
    return ' '.join(processed) # v1.4 - 2026-07-18 - รวมหน่วยเสียงด้วยช่องว่างที่ชัดเจน ช่วยขยายพื้นที่พยัญชนะให้การร้องไพเราะขึ้น

