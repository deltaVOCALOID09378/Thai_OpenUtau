            var list = new List<SingerHubEntry>();
            foreach (var p in Profiles) {
                var entry = new SingerHubEntry {
                    Name = string.IsNullOrWhiteSpace(p.NameTh) ? p.Name : $"{p.Name} ({p.NameTh})",
                    Code = p.Id,
                    Version = "1.0",
                    Company = "DELTA SYNTH",
                    Type = p.Engine.IndexOf("diffsinger", StringComparison.OrdinalIgnoreCase) >= 0 ? "diffsinger" : "utau",
                    Host = "delta",
                    GroupType = p.Type,
                    DownloadUrl = p.DownloadUrl,
                    Tos = "https://deltasynth.com/termsofuse",
                    Icon = $"https://deltasynth.com/assets/images/voicebanks/{p.Name}.png",
                    NameTh = p.NameTh,
                    Voicer = p.Voicer,
                    Genre = p.Genre,
                    Engine = p.Engine
                };
                list.Add(entry);
            }
            return list;
        }
